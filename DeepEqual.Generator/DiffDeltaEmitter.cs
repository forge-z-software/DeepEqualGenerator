    private const string DeepCompareAttributeName = GenCommon.DeepCompareAttributeMetadataName;
    private const string DeltaTrackAttributeName = "DeepEqual.Generator.Shared.DeltaTrackAttribute";
    private const string AccessTrackAttributeName = "DeepEqual.Generator.Shared.AccessTrackAttribute";

    private readonly Dictionary<INamedTypeSymbol, Dictionary<string, int>> _stableIndexTables =
        new(SymbolEqualityComparer.Default);
    private readonly Dictionary<string, (bool Diff, bool Delta)> _emittedDiffDelta = new(StringComparer.Ordinal);

    private bool _useStableIndices;

    public void EmitForRoot(SourceProductionContext spc, DiffDeltaTarget root, string? hintOverride = null)
    {
        Diagnostics.DiagnosticPass(spc, root.Type);

        _useStableIndices = root.GenerateDelta &&
                            (root.StableMode == StableMemberIndexMode.On ||
                             root.StableMode == StableMemberIndexMode.Auto);
        _stableIndexTables.Clear();

        var rootFqn = root.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var sanitizedId = GenCommon.SanitizeIdentifier(rootFqn);
        var hintName = hintOverride ?? GenCommon.SanitizeFileName(rootFqn + ".DeepOpsExtensions.Diff.g.cs");

        var reachable = BuildReachableTypeClosure(root);

        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#pragma warning disable");
        w.Line("using System;");
        w.Line("using System.Collections;");
        w.Line("using System.Collections.Generic;");
        w.Line("using DeepEqual.Generator.Shared;");
        w.Line();

        // namespace + class wrapped with lambda Open so braces are guaranteed correct
        w.Open("namespace DeepEqual", () =>
        {
            w.Open("public static partial class DeepOpsExtensions", () =>
            {
                var ensureDiffName = "__EnsureDiffDelta__" + sanitizedId;
                var guardFieldName = "__ddInit__" + sanitizedId;
                var lockFieldName = "__ddLock__" + sanitizedId;
                var moduleInitName = "__ModuleInit_Diff__" + sanitizedId;

                EmitterCommon.EmitEnsureOnce(
                    w,
                    ensureDiffName,
                    guardFieldName,
                    lockFieldName,
                    writer =>
                    {
                    foreach (var t in reachable.OrderBy(t => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), StringComparer.Ordinal))
                        {
                            var fqn = t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        var id = GenCommon.SanitizeIdentifier(fqn);
                            if (root.GenerateDiff)
                                writer.Line("GeneratedHelperRegistry.RegisterDiff<" + fqn + ">((l, r, c) => TryGetDiff__" + id + "(l, r, c));");
                            if (root.GenerateDelta)
                                writer.Line("GeneratedHelperRegistry.RegisterDelta<" + fqn + ">(ComputeDelta__" + id + ", ApplyDelta__" + id + ");");
                        }
                    });

                EmitterCommon.EmitModuleInitializer(w, moduleInitName, ensureDiffName);

                EmitRootApis(w, root.Type, root.CycleTrackingEnabled, root.GenerateDiff, root.GenerateDelta, ensureDiffName);

                foreach (var t in reachable.OrderBy(t => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                         StringComparer.Ordinal))
                {
                    EmitImplementationsForType(w, t, root);
                }
                if (root.GenerateDelta) EmitSyncApis(w, root, reachable);
            });
        });

        var text = w.ToString();

        var tree = CSharpSyntaxTree.ParseText(text);
        var rootStx = tree.GetRoot();

        var formatted = rootStx.NormalizeWhitespace().ToFullString();
        spc.AddSource(hintName, SourceText.From(formatted, Encoding.UTF8));

        if (HasDeltaTrack(root.Type))
            EmitDeltaTrackPart(spc, root.Type, root);
    }

    private void EmitSyncApis(CodeWriter w, DiffDeltaTarget root, IEnumerable<INamedTypeSymbol> reachable)
    {
        static string Display(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, true);
        static string TypeOf(ITypeSymbol? type) => type is null ? "null" : "typeof(" + Display(type) + ")";
        static string Flag(bool value) => value ? "true" : "false";
        static string Rules(ISymbol symbol) => string.Join("|", symbol.GetAttributes()
            .Where(attribute => attribute.AttributeClass?.ToDisplayString().StartsWith(
                "DeepEqual.Generator.Shared.Deep", StringComparison.Ordinal) == true)
            .Select(attribute => attribute.ToString()).OrderBy(value => value, StringComparer.Ordinal));

        var rootName = Display(root.Type);
        var types = reachable.OrderBy(Display, StringComparer.Ordinal).ToArray();
        var membersByType = types.Select(type => OrderMembers(EnumerateMembers(type, root.IncludeInternals,
            root.IncludeBaseMembers, GetTypeSchema(type))).ToArray()).ToArray();
        var signature = new StringBuilder(rootName);
        signature.Append('|').Append(root.CycleTrackingEnabled).Append('|').Append(root.IncludeBaseMembers)
            .Append('|').Append(root.IncludeInternals).Append('|').Append(root.OrderInsensitiveCollections);
        for (var i = 0; i < types.Length; i++)
        {
            signature.Append('\n').Append(Display(types[i])).Append('|').Append(Rules(types[i]));
            foreach (var member in membersByType[i])
                signature.Append('\n').Append(GetStableMemberIndex(types[i], member).ToString(CultureInfo.InvariantCulture)).Append(':').Append(member.Name)
                    .Append(':').Append(Display(member.Type)).Append(':').Append(CanAssign(member.Symbol, root.IncludeInternals))
                    .Append(':').Append(Rules(member.Symbol));
        }

        var visibility = GenCommon.IsPublicType(root.Type) ? "public" : "internal";
        w.Method($"{visibility} static DeepSync<{rootName}> CreateDeepSync(this {rootName}{(root.Type.IsValueType ? "" : "?")} model, " +
                 $"System.Text.Json.Serialization.Metadata.JsonTypeInfo<{rootName}> snapshot, DeepSyncOptions? options = null)", () =>
        {
            var apply = root.Type.IsValueType
                ? "static (value, delta) => { ApplyDeepDelta(ref value, delta); return value; }"
                : "static (value, delta) => ApplyDeepDelta(value, delta)";
            w.Line($"return new DeepSync<{rootName}>({Literal(signature.ToString())}, snapshot, options,");
            w.Line("static (before, after, rules) => AreDeepEqual(before, after, rules),");
            w.Line("static (before, after, context) => ComputeDeepDelta(before, after, context),");
            w.Line(apply + ",");
            w.Open("new DeepPatchSchema[]", () =>
            {
                for (var i = 0; i < types.Length; i++)
                {
                    var type = types[i];
                    var name = Display(type);
                    w.Line($"new DeepPatchSchema(typeof({name}), new DeepPatchMember[]");
                    w.Open("", () =>
                    {
                        foreach (var member in membersByType[i])
                        {
                            var (kind, _, _, shallow, skip) = ResolveEffectiveSettings(member);
                            if (kind == CompareKind.Skip || skip) continue;
                            ITypeSymbol? key = null;
                            ITypeSymbol? value = null;
                            ITypeSymbol? element = null;
                            if (!TryGetDictionaryTypes(member.Type, out key, out value) && member.Type is not IArrayTypeSymbol)
                                TryGetListInterface(member.Type, out element);
                            var id = GetStableMemberIndex(type, member);
                            var canNest = key is null && element is null && !IsValueLike(member.Type) &&
                                kind == CompareKind.Deep && !shallow;
                            w.Line($"new DeepPatchMember({id}, {Literal(member.Name)}, {TypeOf(member.Type)}, " +
                                   $"static target => (({name})target).@{member.Name}, {Flag(CanAssign(member.Symbol, root.IncludeInternals))}, " +
                                   $"{TypeOf(element)}, {TypeOf(key)}, {TypeOf(value)}, {Flag(canNest)}),");
                        }
                    });
                    w.Line("),");
                }
            });
            w.Line(");");
        });
    }

    private static void EmitRootApis(
        CodeWriter w,
        INamedTypeSymbol rootType,
        bool cycleTrackingEnabled,
        bool generateDiff,
        bool generateDelta,
        string ensureMethodName)
    {
        var fqn = rootType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var id = GenCommon.SanitizeIdentifier(fqn);
        var nullSuffix = rootType.IsValueType ? string.Empty : "?";
        var methodTypeParameters = GenCommon.GetTypeParameterList(rootType);
        var methodConstraints = GenCommon.GetTypeConstraintClauses(rootType);
        var defaultContextExpr = "ctx ?? new DeepEqual.Generator.Shared.ComparisonContext()";

        if (generateDiff)
        {
            var diffSignature =
                "public static (bool has, DeepEqual.Generator.Shared.Diff<" + fqn + "> diff) GetDeepDiff" +
                methodTypeParameters + "(this " + fqn + nullSuffix + " left, " + fqn + nullSuffix +
                " right, DeepEqual.Generator.Shared.ComparisonContext? ctx = null)" + methodConstraints;

            w.Open(diffSignature, () =>
            {
                w.Line(ensureMethodName + "();");
                w.Line("var context = " + defaultContextExpr + ";");
                w.Line("return TryGetDiff__" + id + "(left, right, context);");
            });
            w.Line();
        }

        if (generateDelta)
        {
            w.Line("/// <summary>Computes a delta (patch) from <paramref name=\"left\"/> to <paramref name=\"right\"/>.</summary>");
            w.Line("/// <remarks>");
            w.Line("/// Collections policy:");
            w.Line("/// <list type=\"bullet\">");
            w.Line("/// <item><description><b>Arrays</b>: treated as replace-on-change. Any detected difference emits a single <c>SetMember</c> for that member.</description></item>");
            w.Line("/// <item><description><b>IList&lt;T&gt;</b>: granular sequence ops (<c>SeqReplaceAt</c>/<c>SeqAddAt</c>/<c>SeqRemoveAt</c>) are emitted.</description></item>");
            w.Line("/// <item><description><b>IDictionary</b>/<b>IReadOnlyDictionary</b>: granular key ops (<c>DictSet</c>/<c>DictRemove</c>/<c>DictNested</c>) are emitted.</description></item>");
            w.Line("/// </list>");
            w.Line("/// This mirrors <see cref=\"ApplyDeepDelta(ref " + fqn + nullSuffix + ", DeepEqual.Generator.Shared.DeltaDocument)\"/> behavior, where arrays are not patched item-by-item.</remarks>");

            var computeSignature =
                "public static DeepEqual.Generator.Shared.DeltaDocument ComputeDeepDelta" +
                methodTypeParameters + "(this " + fqn + nullSuffix + " left, " + fqn + nullSuffix +
                " right, DeepEqual.Generator.Shared.ComparisonContext? ctx = null)" + methodConstraints;

            w.Open(computeSignature, () =>
            {
                w.Line(ensureMethodName + "();");
                w.Line("var context = " + defaultContextExpr + ";");
                w.Line($"var doc = DeepEqual.Generator.Shared.DeltaDocument.ForRoot<{fqn}>();");
                w.Line("var writer = new DeepEqual.Generator.Shared.DeltaWriter(doc);");
                w.Line("ComputeDelta__" + id + "(left, right, context, ref writer);");
                w.Line("return doc;");
            });
            w.Line();

            w.Line("/// <summary>Applies a previously computed delta to <paramref name=\"target\"/>.</summary>");
            w.Line("/// <remarks>");
            w.Line("/// Collections policy during application:");
            w.Line("/// <list type=\"bullet\">");
            w.Line("/// <item><description><b>Arrays</b>: always replaced as a whole when a <c>SetMember</c> op is present. Sequence ops are ignored for arrays.</description></item>");
            w.Line("/// <item><description><b>IList&lt;T&gt;</b>: sequence ops are applied in-place (replace/add/remove).</description></item>");
            w.Line("/// <item><description><b>IDictionary</b>/<b>IReadOnlyDictionary</b>: key ops are applied (set/remove) and nested deltas are applied when present.</description></item>");
            w.Line("/// </list>");
            w.Line("/// This matches the generator's policy in delta computation.</remarks>");

            if (!rootType.IsValueType)
            {
                var applyReaderSignature =
                    "public static " + fqn + nullSuffix + " ApplyDeepDelta" + methodTypeParameters +
                    "(this " + fqn + nullSuffix + " target, in DeepEqual.Generator.Shared.DeltaReader reader)" + methodConstraints;

                w.Open(applyReaderSignature, () =>
                {
                    w.Line(ensureMethodName + "();");
                    w.Line("var localReader = reader;");
                    w.Line($"localReader.RequireRoot<{fqn}>();");
                    w.Line("ApplyDelta__" + id + "(ref target, ref localReader);");
                    w.Line("return target;");
                });
                w.Line();

                var applyDocSignature =
                    "public static " + fqn + nullSuffix + " ApplyDeepDelta" + methodTypeParameters +
                    "(this " + fqn + nullSuffix + " target, DeepEqual.Generator.Shared.DeltaDocument delta)" + methodConstraints;

                w.Open(applyDocSignature, () =>
                {
                    w.Line(ensureMethodName + "();");
                    w.Line("var reader = new DeepEqual.Generator.Shared.DeltaReader(delta);");
                    w.Line($"reader.RequireRoot<{fqn}>();");
                    w.Line("ApplyDelta__" + id + "(ref target, ref reader);");
                    w.Line("return target;");
                });
                w.Line();
            }
            else
            {
                var applyReaderSignature =
                    "public static void ApplyDeepDelta" + methodTypeParameters +
                    "(this ref " + fqn + " target, in DeepEqual.Generator.Shared.DeltaReader reader)" + methodConstraints;

                w.Open(applyReaderSignature, () =>
                {
                    w.Line(ensureMethodName + "();");
                    w.Line("var localReader = reader;");
                    w.Line($"localReader.RequireRoot<{fqn}>();");
                    w.Line("ApplyDelta__" + id + "(ref target, ref localReader);");
                });
                w.Line();

                var applyDocSignature =
                    "public static void ApplyDeepDelta" + methodTypeParameters +
                    "(this ref " + fqn + " target, DeepEqual.Generator.Shared.DeltaDocument delta)" + methodConstraints;

                w.Open(applyDocSignature, () =>
                {
                    w.Line(ensureMethodName + "();");
                    w.Line("var reader = new DeepEqual.Generator.Shared.DeltaReader(delta);");
                    w.Line($"reader.RequireRoot<{fqn}>();");
                    w.Line("ApplyDelta__" + id + "(ref target, ref reader);");
                });
                w.Line();
            }
        }
    }

    private static bool IsExpando(ITypeSymbol t)
    {
        return t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == "global::System.Dynamic.ExpandoObject";
    }

    private void EmitDeltaTrackPart(SourceProductionContext spc, INamedTypeSymbol type, DiffDeltaTarget root)
    {
        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        var fqn = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var typeParams = type.Arity > 0 ? "<" + string.Join(",", type.TypeArguments.Select(a => a.Name)) + ">" : "";
        var hint = GenCommon.SanitizeFileName(fqn + ".__DeltaTrack.g.cs");

        static int ToInt(Microsoft.CodeAnalysis.TypedConstant constant) => constant.Value is null ? 0 : Convert.ToInt32(constant.Value);

        var threadSafe = false;
        var typeAccessModeSpecified = false;
        var typeAccessMode = 0;
        var typeAccessGranularitySpecified = false;
        var typeAccessGranularity = 0;
        var typeLogCapacitySpecified = false;
        var typeLogCapacity = 0;

        foreach (var a in type.GetAttributes())
        {
            var full = a.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (AttributeMatches(full, DeltaTrackAttributeName))
            {
                foreach (var kv in a.NamedArguments)
                {
                    switch (kv.Key)
                    {
                        case "ThreadSafe":
                            if (kv.Value.Value is bool ts) threadSafe = ts;
                            break;
                        case "AccessTrack":
                            typeAccessModeSpecified = true;
                            typeAccessMode = ToInt(kv.Value);
                            break;
                        case "AccessGranularity":
                            typeAccessGranularitySpecified = true;
                            typeAccessGranularity = ToInt(kv.Value);
                            break;
                        case "AccessLogCapacity":
                            typeLogCapacitySpecified = true;
                            typeLogCapacity = ToInt(kv.Value);
                            break;
                    }
                }
            }
        }

        var schema = GetTypeSchema(type);
        var members = OrderMembers(EnumerateMembers(type, root.IncludeInternals, root.IncludeBaseMembers, schema)).ToArray();

        var typeDisplayName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        var typeDisplayLiteral = SymbolDisplay.FormatLiteral(typeDisplayName, true);



                var memberCount = members.Length;
        var accessMemberNames = new string[memberCount];
        var accessMemberFlags = new int[memberCount];
        var accessLogPolicies = new int[memberCount];
        var accessForcedLog = new int[memberCount];
        var memberIds = new string[memberCount];
        var trackedMemberIndices = new List<int>(memberCount);
        var hasAccessTracking = false;

        var typeAllowsLog = typeLogCapacitySpecified && typeLogCapacity > 0;

        const int TrackBit = 1;
        const int CountsBit = 2;
        const int LastBit = 4;
        const int CallerBit = 8;
        const int LogAllowedBit = 1;
        const int LogForcedBit = 2;



        for (var i = 0; i < memberCount; i++)
        {
            var member = members[i];
            accessMemberNames[i] = member.Name;
            memberIds[i] = GenCommon.SanitizeIdentifier(member.Name);

            var symbol = member.Symbol;

            var mode = typeAccessModeSpecified ? typeAccessMode : 0;
            var granularity = typeAccessGranularitySpecified ? typeAccessGranularity : 0;
            var logPolicy = typeAllowsLog ? LogAllowedBit : 0;
            var forcedLog = 0;

            AttributeData? accessAttr = null;
            foreach (var attr in symbol.GetAttributes())
            {
                var attrName = attr.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                if (AttributeMatches(attrName, AccessTrackAttributeName))
                {
                    accessAttr = attr;
                    break;
                }
            }

            if (accessAttr is not null)
            {
                mode = 1;
                var propertyGranularity = typeAccessGranularitySpecified ? typeAccessGranularity : 0;
                var propertyGranSpecified = false;
                var propertyLogSpecified = false;
                var propertyLog = 0;

                foreach (var kv in accessAttr.NamedArguments)
                {
                    switch (kv.Key)
                    {
                        case "Mode":
                            mode = ToInt(kv.Value);
                            break;
                        case "Granularity":
                            propertyGranularity = ToInt(kv.Value);
                            propertyGranSpecified = true;
                            break;
                        case "LogCapacity":
                            propertyLog = ToInt(kv.Value);
                            propertyLogSpecified = true;
                            break;
                    }
                }

                if (!propertyGranSpecified && typeAccessGranularitySpecified)
                    propertyGranularity = typeAccessGranularity;

                granularity = propertyGranularity;

                if (propertyLogSpecified)
                {
                    if (propertyLog > 0)
                    {
                        logPolicy = LogAllowedBit | LogForcedBit;
                        forcedLog = propertyLog;
                    }
                    else
                    {
                        logPolicy = typeAllowsLog ? LogAllowedBit : 0;
                        forcedLog = 0;
                    }
                }
                else
                {
                    logPolicy = typeAllowsLog ? LogAllowedBit : 0;
                    forcedLog = 0;
                }
            }
            else
            {
                logPolicy = typeAllowsLog ? LogAllowedBit : 0;
            }

            if (granularity < 0)
                granularity = 0;
            else if (granularity > 2)
                granularity = 2;

            var flags = 0;
            if (mode == 1)
            {
                flags |= TrackBit | CallerBit;
                if (granularity >= 1)
                    flags |= CountsBit;
                if (granularity >= 2)
                    flags |= LastBit;

                hasAccessTracking = true;
                trackedMemberIndices.Add(i);
            }

            accessMemberFlags[i] = flags;
            accessLogPolicies[i] = logPolicy;
            accessForcedLog[i] = forcedLog;
        }




        string FormatStringArrayLiteral(string[] values)

        {

            if (values.Length == 0)

            {

                return "System.Array.Empty<string>()";

            }



            return "new string[] { " + string.Join(", ", values.Select(v => SymbolDisplay.FormatLiteral(v, true))) + " }";

        }



        string FormatFlagsLiteral(int flags)

        {

            if (flags == 0)

            {

                return "AccessMemberFlags.None";

            }



            var parts = new List<string>();

            if ((flags & TrackBit) != 0) parts.Add("AccessMemberFlags.Track");

            if ((flags & CountsBit) != 0) parts.Add("AccessMemberFlags.Counts");

            if ((flags & LastBit) != 0) parts.Add("AccessMemberFlags.Last");

            if ((flags & CallerBit) != 0) parts.Add("AccessMemberFlags.Caller");

            return string.Join(" | ", parts);

        }



        string FormatFlagsArrayLiteral(int[] values)

        {

            if (values.Length == 0)

            {

                return "System.Array.Empty<AccessMemberFlags>()";

            }



            return "new AccessMemberFlags[] { " + string.Join(", ", values.Select(FormatFlagsLiteral)) + " }";

        }



        string FormatLogPolicyLiteral(int policy)

        {

            if (policy == 0)

            {

                return "AccessLogPolicy.None";

            }



            var parts = new List<string>();

            if ((policy & LogAllowedBit) != 0) parts.Add("AccessLogPolicy.Allowed");

            if ((policy & LogForcedBit) != 0) parts.Add("AccessLogPolicy.Forced");

            return string.Join(" | ", parts);

        }



        string FormatLogPolicyArrayLiteral(int[] values)

        {

            if (values.Length == 0)

            {

                return "System.Array.Empty<AccessLogPolicy>()";

            }



            return "new AccessLogPolicy[] { " + string.Join(", ", values.Select(FormatLogPolicyLiteral)) + " }";

        }



        string FormatIntArrayLiteral(int[] values)

        {

            if (values.Length == 0)

            {

                return "System.Array.Empty<int>()";

            }



            return "new int[] { " + string.Join(", ", values.Select(v => FormattableString.Invariant($"{v}"))) + " }";

        }



        var accessMemberNamesLiteral = FormatStringArrayLiteral(accessMemberNames);

        var accessMemberFlagsLiteral = FormatFlagsArrayLiteral(accessMemberFlags);

        var accessLogPolicyLiteral = FormatLogPolicyArrayLiteral(accessLogPolicies);

        var accessForcedLogLiteral = FormatIntArrayLiteral(accessForcedLog);
        var typeLogCapacityLiteral = typeLogCapacitySpecified
            ? FormattableString.Invariant($"{Math.Max(typeLogCapacity, 0)}")
            : "0";

      

                var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#pragma warning disable");
        w.Line("using System;");
        w.Line("using System.Runtime.CompilerServices;");
        w.Line("using System.Threading;");
        w.Line("using DeepEqual.Generator.Shared;");

        void EmitClassBody()
        {
            w.Line("private static readonly string[] __AccessMemberNames = " + accessMemberNamesLiteral + ";");
            w.Line("private static readonly AccessDescriptor __AccessDescriptor = new AccessDescriptor(");
            w.Line("    " + typeDisplayLiteral + ",");
            w.Line("    __AccessMemberNames,");
            w.Line("    " + accessMemberFlagsLiteral + ",");
            w.Line("    " + accessLogPolicyLiteral + ",");
            w.Line("    " + typeLogCapacityLiteral + ",");
            w.Line("    " + accessForcedLogLiteral + ");");
            w.Line("private static readonly MappingInfo __AccessMapping = new MappingInfo(" + typeDisplayLiteral + ", __AccessMemberNames);");
            w.Line("private DeepEqual.Generator.Shared.AccessState __access;");
            w.Line();
            w.Line("private long __dirty0;");
            w.Line("private long[]? __dirtyEx;");
            w.Line("internal const int __DirtyWordShift = 6;");
            w.Line("internal const int __DirtyWordMask = 63;");

            if (threadSafe)
            {
                w.Method("private static long __AtomicOr(ref long location, long mask)", () =>
                {
                    w.Line("long initial, computed;");
                    w.DoWhile("Interlocked.CompareExchange(ref location, computed, initial) != initial", () =>
                    {
                        w.Line("initial = Volatile.Read(ref location);");
                        w.Line("computed = initial | mask;");
                    });
                    w.Line("return computed;");
                });
                            w.Method("private static long __AtomicAnd(ref long location, long mask)", () =>
                {
                    w.Line("long initial, computed;");
                    w.DoWhile("Interlocked.CompareExchange(ref location, computed, initial) != initial", () =>
                    {
                        w.Line("initial = Volatile.Read(ref location);");
                        w.Line("computed = initial & mask;");
                    });
                    w.Line("return computed;");
                });
            }

            w.Line();
            w.Method("private static int __TrailingZeroCount(ulong value)", () =>
            {
                w.If("value == 0", () =>
                {
                    w.Line("return 64;");
                });

                w.Line("int count = 0;");
                w.While("(value & 1UL) == 0", () =>
                {
                    w.Line("count++;");
                    w.Line("value >>= 1;");
                });
                w.Line("return count;");
            });
            w.Line();

            w.Method("[MethodImpl(MethodImplOptions.AggressiveInlining)] internal void __MarkDirty(int bit)", () =>
            {
                w.If("(uint)bit <= 63", () =>
                {
                    if (threadSafe)
                        w.Line("__AtomicOr(ref __dirty0, 1L << bit);");
                    else
                        w.Line("__dirty0 |= 1L << bit;");
                })
                .Else(() =>
                {
                    w.Line("var word = bit >> __DirtyWordShift;");
                    w.Line("var idx = word - 1;");
                    w.Line("var arr = __dirtyEx;");
                    w.If("arr is null || idx >= arr.Length", () =>
                    {
                        w.Line("Array.Resize(ref __dirtyEx, arr is null ? Math.Max(1, idx + 1) : Math.Max(arr.Length * 2, idx + 1));");
                    });
                    if (threadSafe)
                        w.Line("__AtomicOr(ref __dirtyEx![idx], 1L << (bit & __DirtyWordMask));");
                    else
                        w.Line("__dirtyEx![idx] |= 1L << (bit & __DirtyWordMask);");
                });

                if (hasAccessTracking && trackedMemberIndices.Count > 0)
                {
                    SwitchChain.Switch(w, "bit", sw =>
                    {
                        foreach (var index in trackedMemberIndices)
                        {
                            var id = memberIds[index];
                            sw.Case($"__Bit_{id}", () =>
                            {
                                w.Line($"__RecordWrite(__Index_{id});");
                            });
                        }
