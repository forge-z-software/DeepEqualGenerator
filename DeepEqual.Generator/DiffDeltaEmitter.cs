                w.Line("var __raw = reader.AsSpan();");
                w.Line("if (__raw.IsEmpty) return;");

                if (listMembersForFastLane.Count > 0)
                {
                    var targetExists = type.IsValueType ? "" : "target is not null && ";
                    w.If(targetExists + "__raw[0].Kind == DeltaKind.SeqAddAt", () =>
