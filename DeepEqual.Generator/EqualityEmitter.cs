namespace DeepEqual.Generator;

internal sealed class EqualityEmitter
{
    private const string DeepCompareAttributeName = GenCommon.DeepCompareAttributeMetadataName;
    internal static string RootComparer(INamedTypeSymbol root) => "__CompareRoot_" + GenCommon.SanitizeIdentifier(
        GenCommon.SanitizeFileName(root.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "_DeepEqual.g.cs"));

    internal static string PatchCompareName(INamedTypeSymbol owner, string member) =>
        "__PatchCompare_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + member);

    public void EmitForRoot(SourceProductionContext spc, EqualityTarget root, string? hintOverride = null,
        bool replacementDiff = false, bool replacementDelta = false, bool patchComparers = false)
    {
        var rootFqn = root.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var hintName = hintOverride ?? GenCommon.SanitizeFileName(rootFqn + ".DeepOpsExtensions.Equality.g.cs");

        var reachable = GenCommon.BuildReachableTypeClosure(root);
        var trackCycles = root.CycleTrackingEnabled && GenCommon.CanContainCycles(root, reachable);
        var accessibility = !GenCommon.IsPublicType(root.Type)
            ? "internal"
            : "public";
        var methodTypeParameters = GenCommon.GetTypeParameterList(root.Type);
        var methodConstraints = GenCommon.GetTypeConstraintClauses(root.Type);
        var nullSuffix = root.Type.IsReferenceType ? "?" : string.Empty;
        var rootComparer = RootComparer(root.Type);
        var rootComparerType = rootComparer + methodTypeParameters;
        var helperName = GenCommon.GetHelperMethodName(root.Type);

        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("#pragma warning disable");
        w.Line("using System;");
        w.Line("using System.Collections;");
        w.Line("using System.Collections.Generic;");
        w.Line("using DeepEqual.Generator.Shared;");
        w.Line();

        w.Open("namespace DeepEqual", () =>
        {
            w.Open("public static partial class DeepOpsExtensions", () =>
            {
                if (methodTypeParameters.Length == 0)
                {
                    w.Line("[System.Runtime.CompilerServices.ModuleInitializer]");
                    w.Method("internal static void __Register_" + rootComparer + "()", () =>
                    {
                        w.Line("GeneratedHelperRegistry.RegisterComparer<" + rootFqn + ">(" + rootComparer + "." + helperName + ");");
                        foreach (var type in reachable.Where(type => !SymbolEqualityComparer.Default.Equals(type, root.Type) &&
                                     GenCommon.IsTypeAccessibleFromRoot(type, root))
                                     .OrderBy(type => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), StringComparer.Ordinal))
                        {
                            var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                            w.Line("GeneratedHelperRegistry.RegisterReachableComparer<" + typeName + ">(" +
                                   rootComparer + "." + GenCommon.GetHelperMethodName(type) + ");");
                        }
                    });
                }

                var defaultContextExpr = trackCycles
                    ? "new DeepEqual.Generator.Shared.ComparisonContext()"
                    : "DeepEqual.Generator.Shared.ComparisonContext.NoTracking";

                var methodSignature = accessibility + " static bool AreDeepEqual" + methodTypeParameters +
                                      "(this " + rootFqn + nullSuffix + " left, " + rootFqn + nullSuffix +
                                      " right, DeepEqual.Generator.Shared.ComparisonContext? ctx = null)" + methodConstraints;

                w.Method(methodSignature, () =>
                {
                    if (!root.Type.IsValueType)
                    {
                        w.If("object.ReferenceEquals(left, right)", () =>
                        {
                            w.Line("return true;");
                        });
                        w.If("left is null || right is null", () =>
                        {
                            w.Line("return false;");
                        });
                    }

                    w.Line("var context = ctx ?? " + defaultContextExpr + ";");
                    w.Line("return " + rootComparerType + "." + helperName + "(left, right, context);");
                });
                w.Line();

                var optionsSignature = accessibility + " static bool AreDeepEqual" + methodTypeParameters +
                                       "(this " + rootFqn + nullSuffix + " left, " + rootFqn + nullSuffix +
                                       " right, DeepEqual.Generator.Shared.ComparisonOptions options)" + methodConstraints;

                w.Method(optionsSignature, () =>
                {
                    w.Line("var context = new DeepEqual.Generator.Shared.ComparisonContext(options);");
                    w.Line("return AreDeepEqual(left, right, context);");
                });
                w.Line();

                var mismatchSignature = accessibility + " static DeepMismatch? GetDeepMismatch" + methodTypeParameters +
                    "(this " + rootFqn + nullSuffix + " expected, " + rootFqn + nullSuffix +
                    " actual, ComparisonOptions? options = null)" + methodConstraints;
                w.Method(mismatchSignature, () =>
                {
                    w.Line("var context = ComparisonContext.ForMismatch(options, " + (trackCycles ? "true" : "false") + ");");
                    w.Line("if (AreDeepEqual(expected, actual, context)) return null;");
                    w.Line("context.RecordMismatch(expected, actual);");
                    w.Line("return context.Mismatch;");
                });

                w.Method(accessibility + " static DeepModel ExplainDeepModel" + methodTypeParameters +
                    "(this " + rootFqn + nullSuffix + " model)" + methodConstraints, () =>
                    w.Line("return " + rootComparerType + ".Model;"));

                var reportSignature = accessibility + " static DeepChangeReport DescribeDeepChanges" + methodTypeParameters +
                    "(this " + rootFqn + nullSuffix + " before, " + rootFqn + nullSuffix +
                    " after, ComparisonOptions? options = null, int maxChanges = 100)" + methodConstraints;
                w.Method(reportSignature, () =>
                {
                    w.Line("var context = ComparisonContext.ForReport(options, maxChanges, " +
                           (trackCycles ? "true" : "false") + ");");
                    w.Line("if (!AreDeepEqual(before, after, context)) context.RecordMismatch(before, after);");
                    w.Line("return context.GetReport();");
                });
                w.Method(accessibility + " static void AssertDeepEqual" + methodTypeParameters +
                    "(this " + rootFqn + nullSuffix + " expected, " + rootFqn + nullSuffix +
                    " actual, ComparisonOptions? options = null, ChangeFormatOptions? format = null, int maxChanges = 20)" +
                    methodConstraints, () =>
                {
                    w.Line("if (!AreDeepEqual(expected, actual, options is null ? null : new ComparisonContext(options)))");
                    w.Line("    throw new DeepComparisonException(DescribeDeepChanges(expected, actual, options, maxChanges), format);");
                });

                if (replacementDiff || replacementDelta)
                    EmitReplacementApis(w, root, accessibility, rootFqn + nullSuffix, rootFqn, methodTypeParameters,
                        methodConstraints, replacementDiff, replacementDelta);

                w.Open("private static class " + rootComparerType + methodConstraints, () =>
                {
                    EmitModel(w, root, reachable, trackCycles);
                    var emittedComparers = new HashSet<string>(StringComparer.Ordinal);
                    var comparerDeclarations = new List<string[]>();
                    foreach (var t in reachable.OrderBy(t => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                                 StringComparer.Ordinal))
                        EmitHelperForType(w, t, root, trackCycles, emittedComparers, comparerDeclarations, spc, patchComparers);

                    foreach (var block in comparerDeclarations)
                        foreach (var line in block)
                            w.Line(line);
                });
            });
        });

        var text = w.ToString();
        var tree = CSharpSyntaxTree.ParseText(text);
        var rootStx = tree.GetRoot();

        var formatted = rootStx.NormalizeWhitespace().ToFullString();
        spc.AddSource(hintName, SourceText.From(formatted, Encoding.UTF8));
    }

    private static void EmitReplacementApis(CodeWriter w, EqualityTarget root, string accessibility, string argumentType,
        string rootType, string parameters, string constraints, bool diff, bool delta)
    {
        if (diff)
            w.Method($"{accessibility} static (bool has, Diff<{rootType}> diff) GetDeepDiff{parameters}" +
                     $"(this {argumentType} before, {argumentType} after, ComparisonContext? ctx = null){constraints}", () =>
            {
                w.Line($"return AreDeepEqual(before, after, ctx) ? (false, Diff<{rootType}>.Empty) : (true, Diff<{rootType}>.Replacement(after));");
            });
        if (!delta) return;

        w.Method($"{accessibility} static DeltaDocument ComputeDeepDelta{parameters}" +
                 $"(this {argumentType} before, {argumentType} after, ComparisonContext? ctx = null){constraints}", () =>
        {
            w.Line($"var document = DeltaDocument.ForRoot<{rootType}>();");
            w.Line("if (!AreDeepEqual(before, after, ctx)) new DeltaWriter(document).WriteReplaceObject(after);");
            w.Line("return document;");
        });

        var returnsRoot = !root.Type.IsValueType;
        w.Method($"{accessibility} static {(returnsRoot ? argumentType : "void")} ApplyDeepDelta{parameters}" +
                 $"(this {(returnsRoot ? "" : "ref ")}{argumentType} target, DeltaDocument delta){constraints}", () =>
        {
            w.Line($"var reader = new DeltaReader(delta); reader.RequireRoot<{rootType}>();");
            w.Line("var operations = reader.AsSpan();");
            w.Line(returnsRoot ? "if (operations.IsEmpty) return target;" : "if (operations.IsEmpty) return;");
            w.Line("if (operations.Length != 1 || operations[0].Kind != DeltaKind.ReplaceObject || operations[0].MemberIndex != -1)");
            w.Line("    throw new InvalidOperationException(\"This model uses root replacement patches.\");");
            w.Line($"{(returnsRoot ? "return" : "target =")} ({argumentType})operations[0].Value;");
        });

        var metadata = string.Join("|", root.ExternalRules?.OrderBy(pair => pair.Key.Name, StringComparer.Ordinal)
            .Select(pair => pair.Key.Name + ":" + pair.Value) ?? Enumerable.Empty<string>());
        var signature = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(rootType + ":" + metadata, true);
        w.Method($"{accessibility} static DeepSync<{rootType}> CreateDeepSync{parameters}(this {argumentType} model, " +
                 $"System.Text.Json.Serialization.Metadata.JsonTypeInfo<{rootType}> snapshot, DeepSyncOptions? options = null){constraints}", () =>
        {
            var apply = returnsRoot
                ? "static (value, patch) => ApplyDeepDelta(value, patch)"
                : "static (value, patch) => { ApplyDeepDelta(ref value, patch); return value; }";
            w.Line($"return new DeepSync<{rootType}>({signature}, snapshot, options,");
            w.Line("static (before, after, rules) => AreDeepEqual(before, after, rules),");
            w.Line("static (before, after, context) => ComputeDeepDelta(before, after, context),");
            w.Line(apply + ", []);");
        });
    }

    private static void EmitModel(CodeWriter w, EqualityTarget root, IEnumerable<INamedTypeSymbol> reachable,
        bool trackCycles)
    {
        static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);
        static string Display(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        w.Open("internal static DeepModel Model => new(" + Literal(Display(root.Type)) + ", " +
               (trackCycles ? "true" : "false") + ", new DeepModelMember[]", () =>
        {
            foreach (var type in reachable.OrderBy(Display, StringComparer.Ordinal))
            {
                var schema = GenCommon.GetTypeSchema(type);
                var candidates = new EqualityTypeSchema([], []);
                foreach (var member in GenCommon.OrderMembers(GenCommon.EnumerateMembers(
                             type, root.IncludeInternals, root.IncludeBaseMembers, candidates)))
                {
                    var rule = root.GetMemberRule(member.Symbol);
                    var kind = GenCommon.GetEffectiveKind(member.Type, rule);
                    var mode = kind.ToString();
                    if (kind == EffectiveKind.Skip || schema.IgnoreMembers.Contains(member.Name, StringComparer.Ordinal) ||
                        schema.IncludeMembers.Count != 0 && !schema.IncludeMembers.Contains(member.Name, StringComparer.Ordinal))
                        mode = "Skipped";
                    else if (GenCommon.GetEffectiveComparerType(member.Type, rule) is not null)
                        mode = "Custom";

                    var collection = "None";
                    var keys = "";
                    ITypeSymbol? element = null;
                    if (mode == "Deep" && !IsTerminalComparison(member.Type, rule, kind))
                    {
                        if (GenCommon.TryGetDictionaryInterface(member.Type, out _, out element))
                            collection = "Dictionary";
                        else if (member.Type is IArrayTypeSymbol array)
                            element = array.ElementType;
                        else if (!GenCommon.TryGetReadOnlyMemory(member.Type, out element) &&
                                 !GenCommon.TryGetMemory(member.Type, out element))
                            GenCommon.TryGetEnumerableInterface(member.Type, out element);

                        if (element is not null && collection == "None")
                        {
                            var unordered = member.Type is not IArrayTypeSymbol { Rank: > 1 } &&
                                            GenCommon.ResolveOrderInsensitive(root.OrderInsensitiveCollections, rule, element, type);
                            collection = unordered ? "Unordered" : "Ordered";
                            if (GenCommon.TryGetKeySpec(element, rule, root, out _, out _))
                            {
                                if (unordered) collection = "Keyed";
                                keys = string.Join(", ", GenCommon.GetConfiguredKeyNames(element, rule));
                            }
                        }
                    }

                    var runtimeType = element ?? member.Type;
                    var fallback = mode == "Deep" && (runtimeType.TypeKind is TypeKind.Interface or TypeKind.TypeParameter ||
                                                      runtimeType.SpecialType == SpecialType.System_Object);
                    w.Line("new DeepModelMember(" + Literal(Display(type)) + ", " + Literal(member.Name) + ", " +
                           Literal(Display(member.Type)) + ", DeepMemberMode." + mode + ", DeepCollectionMode." +
                           collection + ", " + Literal(keys) + ", " + (fallback ? "true" : "false") + "),");
                }
            }
        });
        w.Line(");");
    }

    private void EmitHelperForType(CodeWriter w, INamedTypeSymbol type, EqualityTarget root, bool trackCycles,
        HashSet<string> emittedComparers, List<string[]> comparerDeclarations, SourceProductionContext spc, bool patchComparers)
    {
        var fqn = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var helper = GenCommon.GetHelperMethodName(type);
        var schema = GenCommon.GetTypeSchema(type);
        var members = GenCommon.OrderMembers(
            GenCommon.EnumerateMembers(type, root.IncludeInternals, root.IncludeBaseMembers, schema)).ToArray();
        var terminalType = members.All(member =>
        {
            var rule = root.GetMemberRule(member.Symbol);
            return IsTerminalComparison(member.Type, rule, GenCommon.GetEffectiveKind(member.Type, rule));
        });

        w.Method("internal static bool " + helper + "(" + fqn + " left, " + fqn +
                 " right, DeepEqual.Generator.Shared.ComparisonContext context)", () =>
                 {
                     if (!type.IsValueType)
                     {
                         w.If("object.ReferenceEquals(left, right)", () =>
                         {
                             w.Line("return true;");
                         });
                         w.If("left is null || right is null", () =>
                         {
                             w.Line("return false;");
                         });

                         if (trackCycles && !terminalType)
                         {
                             w.If("!context.Enter(left, right)", () =>
                             {
                                 w.Line("return true;");
                             });
                             TryChain.Try(w, () =>
                             {
                                 EmitBody();
                                 w.Line("return true;");
                             })
                         .Finally(() =>
                    {
                        w.Line("context.Exit(left, right);");
                    });
                             return;
                         }
                     }

                     EmitBody();
                     w.Line("return true;");

                     void EmitBody()
                     {
                         var inc = schema.IncludeMembers;
                         var ign = schema.IgnoreMembers;
                         var schemaAttribute = GenCommon.GetDeepCompareAttribute(type);
                         foreach (var name in inc.Concat(ign).Distinct(StringComparer.Ordinal))
                         {
                             if (GenCommon.FindMemberOn(type, name, root.IncludeInternals, root.IncludeBaseMembers) is not null)
                                 continue;

                             var location = schemaAttribute?.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation()
                                 ?? type.Locations.FirstOrDefault();
                             spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ004, location,
                                 $"'{name}' is not a readable member of '{type}' under the configured rules."));
                         }

                         if (inc.Count > 0 && ign.Count > 0)
                             for (var i = 0; i < inc.Count; i++)
                             {
                                 var name = inc[i];
                                 if (ign.Contains(name, StringComparer.Ordinal))
                                 {
                                     var attr = type.GetAttributes()
                                     .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == DeepCompareAttributeName);
                                     var loc = attr?.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation() ??
                                           type.Locations.FirstOrDefault();
                                     if (loc is not null) spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ001, loc, name));
                                     break;
                                 }
                             }

                         foreach (var member in members)
                         {
                             var rule = root.GetMemberRule(member.Symbol);
                             var kind = GenCommon.GetEffectiveKind(member.Type, rule);
                             if (kind == EffectiveKind.Skip || !ValidateMemberRule(member, rule, kind, spc))
                                 continue;

                             w.Open(string.Empty, () =>
                             {
                                 var memberName = SyntaxFacts.GetKeywordKind(member.Name) != SyntaxKind.None
                                     ? "@" + member.Name
                                     : member.Name;
                                 var literalName = Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(member.Name, true);
                                 w.Line("var expected = left." + memberName + ";");
                                 w.Line("var actual = right." + memberName + ";");
                                 if (IsTerminalComparison(member.Type, rule, kind))
                                 {
                                     var next = "__next_" + GenCommon.SanitizeIdentifier(member.Name);
                                     EmitMember(w, type, member, root, emittedComparers, comparerDeclarations, spc,
                                         "if (!context.RecordMemberMismatch(" + literalName +
                                         ", expected, actual)) return false; else goto " + next + ";");
                                     w.Line(next + ": ;");
                                     return;
                                 }

                                 w.If("context.IsRecordingMismatch", () =>
                                 {
                                     w.Line("using var path = context.AtMember(" + literalName + ");");
                                     w.Line("if (!CompareMember() && !context.RecordMismatch(expected, actual)) return false;");
                                 }).ElseIf("!CompareMember()", () => w.Line("return false;"));
                                 w.Method("bool CompareMember()", () =>
                                 {
                                     EmitMember(w, type, member, root, emittedComparers, comparerDeclarations, spc);
                                     w.Line("return true;");
                                 });
                             });
                         }
                     }
                 });

        w.Line();
        if (!patchComparers) return;
        foreach (var member in members)
        {
            var rule = root.GetMemberRule(member.Symbol);
            var kind = GenCommon.GetEffectiveKind(member.Type, rule);
            if (kind == EffectiveKind.Skip || !GenCommon.NeedsExactPatchComparison(member.Type, rule, type,
                    root.OrderInsensitiveCollections, root.IncludeInternals, root.IncludeBaseMembers)) continue;
            w.Method($"internal static bool {PatchCompareName(type, member.Name)}({fqn} left, {fqn} right, ComparisonContext context)", () =>
            {
                w.Line("var expected = left.@" + member.Name + ";");
                w.Line("var actual = right.@" + member.Name + ";");
                EmitMember(w, type, member, root, emittedComparers, comparerDeclarations, spc);
                w.Line("return true;");
            });
        }
    }

    private static bool IsTerminalComparison(ITypeSymbol type, AttributeData? rule, EffectiveKind kind)
    {
        if (kind is EffectiveKind.Shallow or EffectiveKind.Reference or EffectiveKind.Skip ||
            GenCommon.GetEffectiveComparerType(type, rule) is not null)
            return true;

        if (type is INamedTypeSymbol nullable && nullable.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            return IsTerminalComparison(nullable.TypeArguments[0], rule, EffectiveKind.Deep);

        return type.SpecialType == SpecialType.System_String || type.TypeKind == TypeKind.Enum ||
            GenCommon.IsWellKnownStruct(type) || (type.IsValueType && type.SpecialType != SpecialType.None);
    }

    private void EmitMember(CodeWriter w, INamedTypeSymbol owner, EqualityMemberSymbol equalityMember,
        EqualityTarget root,
        HashSet<string> emittedComparers, List<string[]> comparerDeclarations, SourceProductionContext spc,
        string failure = "return false;")
    {
        const string leftExpr = "expected";
        const string rightExpr = "actual";
        var deepAttr = root.GetMemberRule(equalityMember.Symbol);
        var kind = GenCommon.GetEffectiveKind(equalityMember.Type, deepAttr);

        {
            var all = equalityMember.Symbol.GetAttributes()
                .Where(a => a.AttributeClass?.ToDisplayString() == DeepCompareAttributeName).ToArray();
            if (all.Length > 1)
            {
                var loc = all[0].ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation() ??
                          equalityMember.Symbol.Locations.FirstOrDefault();
                if (loc is not null)
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ001, loc, equalityMember.Name));
            }

            if (kind == EffectiveKind.Deep)
            {
                var t = equalityMember.Type;
                if (t is INamedTypeSymbol n && GenCommon.IsUserObjectType(n) && !GenCommon.IsTypeAccessibleFromRoot(n, root))
                {
                    var attr = all.FirstOrDefault();
                    var loc2 = attr?.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation() ??
                               equalityMember.Symbol.Locations.FirstOrDefault();
                    if (loc2 is not null)
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ002, loc2,
                            n.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));
                }
            }
        }

        if (kind == EffectiveKind.Skip)
        {
            w.Line();
            return;
        }

        var isString = equalityMember.Type.SpecialType == SpecialType.System_String;
        if (!equalityMember.Type.IsValueType && !isString)
        {
            w.If($"!object.ReferenceEquals({leftExpr}, {rightExpr})", () =>
            {
                w.If($"{leftExpr} is null || {rightExpr} is null", () =>
                {
                    w.Line(failure);
                });
            });
        }

        if (kind == EffectiveKind.Reference)
        {
            w.If($"!object.ReferenceEquals({leftExpr}, {rightExpr})", () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        var directCustomCmp = GenCommon.GetEffectiveComparerType(equalityMember.Type, deepAttr);
        if (directCustomCmp is not null)
        {
            var cmpFqn = directCustomCmp.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var tFqn = equalityMember.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var customVar = "__cmp_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                            GenCommon.SanitizeIdentifier(equalityMember.Name);
            w.Line("var " + customVar + " = (System.Collections.Generic.IEqualityComparer<" + tFqn +
                   ">)new " + cmpFqn + "();");
            w.If("!" + customVar + ".Equals(" + leftExpr + ", " + rightExpr + ")", () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        if (kind == EffectiveKind.Shallow)
        {
            w.If("!object.Equals(" + leftExpr + ", " + rightExpr + ")", () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        if (equalityMember.Type is INamedTypeSymbol nnt0 &&
            nnt0.OriginalDefinition.ToDisplayString() == "System.Nullable<T>")
        {
            var valueT = nnt0.TypeArguments[0];
            var customCmpT = GenCommon.GetEffectiveComparerType(valueT, deepAttr);
            string? customVar = null;
            if (customCmpT is not null)
            {
                var cmpFqn = customCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var elFqn2 = valueT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                customVar = "__cmp_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                            GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + customVar + " = (System.Collections.Generic.IEqualityComparer<" + elFqn2 +
                       ">)new " + cmpFqn + "();");
            }

            w.If(leftExpr + ".HasValue != " + rightExpr + ".HasValue", () =>
            {
                w.Line(failure);
            });
            w.If(leftExpr + ".HasValue", () =>
            {
                if (customVar is not null)
                {
                    w.If("!" + customVar + ".Equals(" + leftExpr + ".Value, " + rightExpr + ".Value)", () =>
                    {
                        w.Line(failure);
                    });
                }
                else
                {
                    EmitNullableValueCompare_NoCustom(w, leftExpr, rightExpr, valueT, failure);
                }
            });
            w.Line();
            return;
        }

        if (GenCommon.TryEmitWellKnownStructCompare(w, leftExpr, rightExpr, equalityMember.Type, failure))
        {
            w.Line();
            return;
        }

        if (equalityMember.Type.SpecialType == SpecialType.System_String)
        {
            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualStrings(" + leftExpr + ", " + rightExpr + ", context)", () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        if (equalityMember.Type.TypeKind == TypeKind.Enum)
        {
            var enumFqn = equalityMember.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualEnum<" + enumFqn + ">(" + leftExpr +
                  ", " + rightExpr + ")", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (GenCommon.IsNumericWithTolerance(equalityMember.Type))
        {
            var call = GenCommon.GetNumericCall(equalityMember.Type, leftExpr, rightExpr, "context");
            w.If("!" + call, () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        if (GenCommon.TryGetReadOnlyMemory(equalityMember.Type, out var romEl))
        {
            var elFqn = romEl!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var elKind = GenCommon.GetEffectiveKind(romEl, null);
            var elemCustomCmpT = GenCommon.GetEffectiveComparerType(romEl, deepAttr);
            string? elemCustomVar = null;
            if (elemCustomCmpT is not null)
            {
                var cmpFqn = elemCustomCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                elemCustomVar = "__cmpE_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                                GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + elemCustomVar + " = (System.Collections.Generic.IEqualityComparer<" + elFqn +
                       ">)new " + cmpFqn + "();");
            }

            var cmpName = GenCommon.EnsureComparerStruct(emittedComparers, comparerDeclarations, romEl, elKind,
                "M_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)) +
                "_" + equalityMember.Name, elemCustomVar);

            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualReadOnlyMemory<" + elFqn + ", " + cmpName +
                  ">(" + leftExpr + ", " + rightExpr + ", new " + cmpName + "(" + (elemCustomVar ?? "") +
                  "), context)", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (GenCommon.TryGetMemory(equalityMember.Type, out var memEl))
        {
            var elFqn = memEl!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var elKind = GenCommon.GetEffectiveKind(memEl, null);
            var elemCustomCmpT = GenCommon.GetEffectiveComparerType(memEl, deepAttr);
            string? elemCustomVar = null;
            if (elemCustomCmpT is not null)
            {
                var cmpFqn = elemCustomCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                elemCustomVar = "__cmpE_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                                GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + elemCustomVar + " = (System.Collections.Generic.IEqualityComparer<" + elFqn +
                       ">)new " + cmpFqn + "();");
            }

            var cmpName = GenCommon.EnsureComparerStruct(emittedComparers, comparerDeclarations, memEl, elKind,
                "M_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)) +
                "_" + equalityMember.Name, elemCustomVar);

            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualMemory<" + elFqn + ", " + cmpName + ">(" +
                  leftExpr + ", " + rightExpr + ", new " + cmpName + "(" + (elemCustomVar ?? "") + "), context)", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (equalityMember.Type.IsValueType && equalityMember.Type.SpecialType != SpecialType.None)
        {
            w.If("!" + leftExpr + ".Equals(" + rightExpr + ")", () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        if (equalityMember.Type is IArrayTypeSymbol arr)
        {
            var el = arr.ElementType;
            var elFqn = el.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var unordered = arr.Rank == 1 && GenCommon.ResolveOrderInsensitive(root.OrderInsensitiveCollections, deepAttr, el, owner);
            var elKind = GenCommon.GetEffectiveKind(el, null);

            var elemCustomCmpT = GenCommon.GetEffectiveComparerType(el, deepAttr);
            string? elemCustomVar = null;
            if (elemCustomCmpT is not null)
            {
                var cmpFqn = elemCustomCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                elemCustomVar = "__cmpE_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                                GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + elemCustomVar + " = (System.Collections.Generic.IEqualityComparer<" + elFqn +
                       ">)new " + cmpFqn + "();");
            }

            var cmpName = GenCommon.EnsureComparerStruct(emittedComparers, comparerDeclarations, el, elKind,
                "M_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)) +
                "_" + equalityMember.Name, elemCustomVar);

            if (unordered)
            {
                EmitUnordered(w, el, deepAttr, root, cmpName, elemCustomVar, leftExpr, rightExpr, spc);
            }
            else
            {
                var helper = arr.Rank == 1 ? "AreEqualArrayRank1" : "AreEqualArray";
                var compare = "ComparisonHelpers." + helper + "<" + elFqn + ", " + cmpName + ">(" +
                              leftExpr + ", " + rightExpr + ", new " + cmpName + "(" + (elemCustomVar ?? "") + "), context)";
                EmitOrdered(w, el, arr.Rank == 1, deepAttr, root, cmpName, elemCustomVar, leftExpr, rightExpr, compare, failure, spc);
            }

            w.Line();
            return;
        }

        if (GenCommon.TryGetDictionaryInterface(equalityMember.Type, out var keyT, out var valT))
        {
            var kFqn = keyT!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var vFqn = valT!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var vKind = GenCommon.GetEffectiveKind(valT, null);

            var valCustomCmpT = GenCommon.GetEffectiveComparerType(valT, deepAttr);
            string? valCustomVar = null;
            if (valCustomCmpT is not null)
            {
                var cmpFqn = valCustomCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                valCustomVar = "__cmpV_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                               GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + valCustomVar + " = (System.Collections.Generic.IEqualityComparer<" + vFqn +
                       ">)new " + cmpFqn + "();");
            }

            var cmpAny = GenCommon.EnsureComparerStruct(
                emittedComparers, comparerDeclarations, valT, vKind,
                "M_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)) +
                "_" + equalityMember.Name + "_Val",
                valCustomVar
            );

            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualDictionariesAny<" + kFqn + ", " + vFqn +
                  ", " + cmpAny + ">(" + leftExpr + ", " + rightExpr + ", new " + cmpAny + "(" + (valCustomVar ?? "") + "), context)", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (GenCommon.TryGetEnumerableInterface(equalityMember.Type, out var elT))
        {
            var elFqn = elT!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var elKind = GenCommon.GetEffectiveKind(elT, null);
            var unordered = GenCommon.ResolveOrderInsensitive(root.OrderInsensitiveCollections, deepAttr, elT, owner);

            var elemCustomCmpT = GenCommon.GetEffectiveComparerType(elT, deepAttr);
            string? elemCustomVar = null;
            if (elemCustomCmpT is not null)
            {
                var cmpFqn = elemCustomCmpT.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                elemCustomVar = "__cmpE_" + GenCommon.SanitizeIdentifier(owner.Name) + "_" +
                                GenCommon.SanitizeIdentifier(equalityMember.Name);
                w.Line("var " + elemCustomVar + " = (System.Collections.Generic.IEqualityComparer<" + elFqn +
                       ">)new " + cmpFqn + "();");
            }

            var cmpName = GenCommon.EnsureComparerStruct(emittedComparers, comparerDeclarations, elT, elKind,
                "M_" + GenCommon.SanitizeIdentifier(owner.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)) +
                "_" + equalityMember.Name, elemCustomVar);
            if (unordered)
            {
                EmitUnordered(w, elT, deepAttr, root, cmpName, elemCustomVar, leftExpr, rightExpr, spc);
            }
            else
            {
                var compare = "ComparisonHelpers.AreEqualSequencesOrdered<" + elFqn + ", " + cmpName + ">(" +
                              leftExpr + ", " + rightExpr + ", new " + cmpName + "(" + (elemCustomVar ?? "") + "), context)";
                EmitOrdered(w, elT, true, deepAttr, root, cmpName, elemCustomVar, leftExpr, rightExpr, compare, failure, spc);
            }

            w.Line();
            return;
        }

        if ((equalityMember.Type.TypeKind == TypeKind.Interface ||
             equalityMember.Type is INamedTypeSymbol { IsAbstract: true })
            && !(GenCommon.TryGetDictionaryInterface(equalityMember.Type, out _, out _) ||
                 GenCommon.TryGetEnumerableInterface(equalityMember.Type, out _)))
        {
            var declFqn = equalityMember.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.DeepComparePolymorphic<" + declFqn + ">(" +
                  leftExpr + ", " + rightExpr + ", context)", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (equalityMember.Type.SpecialType == SpecialType.System_Object || equalityMember.Type is ITypeParameterSymbol)
        {
            w.If("!DeepEqual.Generator.Shared.DynamicDeepComparer.AreEqualDynamic(" + leftExpr + ", " +
                  rightExpr + ", context)", () =>
                  {
                      w.Line(failure);
                  });
            w.Line();
            return;
        }

        if (equalityMember.Type is INamedTypeSymbol nts && GenCommon.IsUserObjectType(nts)
                                                        && !(nts.IsAbstract || nts.TypeKind == TypeKind.Interface))
        {
            var helperExpr = GenCommon.GetHelperMethodName(nts) + "(" + leftExpr + ", " + rightExpr + ", context)";
            w.If("!" + helperExpr, () =>
            {
                w.Line(failure);
            });
            w.Line();
            return;
        }

        w.If("!object.Equals(" + leftExpr + ", " + rightExpr + ")", () =>
        {
            w.Line(failure);
        });
        w.Line();
    }

    private static bool ValidateMemberRule(EqualityMemberSymbol member, AttributeData? attribute, EffectiveKind kind,
        SourceProductionContext spc)
    {
        var location = attribute?.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation()
                       ?? member.Symbol.Locations.FirstOrDefault();
        if (member.Type.IsRefLikeType || member.Type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer)
            return Report($"Member '{member.Name}' has a type that cannot be compared. Mark it with CompareKind.Skip.");
        if (kind == EffectiveKind.Reference && member.Type.IsValueType)
            return Report($"Reference comparison requires a reference type on '{member.Name}'.");
        if (attribute is null) return true;

        foreach (var rule in attribute.NamedArguments)
        {
            if (rule.Key is "Members" or "IgnoreMembers" && rule.Value.Values.Length > 0)
                return Report($"Apply {rule.Key} to the type that declares those members.");

            if (rule.Key == "KeyMembers" && rule.Value.Values.Length > 0 &&
                ((member.Type is not IArrayTypeSymbol { Rank: 1 } &&
                  !GenCommon.TryGetEnumerableInterface(member.Type, out _)) ||
                 GenCommon.TryGetDictionaryInterface(member.Type, out _, out _)))
                return Report($"KeyMembers on '{member.Name}' requires a list or one-dimensional array.");

            if (rule is { Key: "ComparerType", Value.Value: INamedTypeSymbol custom })
            {
                ITypeSymbol? element = null;
                if (member.Type is IArrayTypeSymbol array)
                    element = array.ElementType;
                else if (member.Type is INamedTypeSymbol nullable && nullable.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
                    element = nullable.TypeArguments[0];
                else if (!GenCommon.TryGetDictionaryInterface(member.Type, out _, out element) &&
                         !GenCommon.TryGetReadOnlyMemory(member.Type, out element) &&
                         !GenCommon.TryGetMemory(member.Type, out element))
                    GenCommon.TryGetEnumerableInterface(member.Type, out element);

                var canConstruct = custom.IsValueType ||
                    custom.InstanceConstructors.Any(ctor => ctor.Parameters.Length == 0 &&
                        ctor.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal);
                if (custom.IsAbstract || !canConstruct || (!GenCommon.ImplementsIEqualityComparerFor(custom, member.Type) &&
                    (element is null || !GenCommon.ImplementsIEqualityComparerFor(custom, element))))
                    return Report($"Comparer '{custom}' needs an accessible parameterless constructor and must implement IEqualityComparer<T> for '{member.Name}' or its element type.");
            }
        }
        return true;

        bool Report(string message)
        {
            spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ004, location, message));
            return false;
        }
    }

    private static void EmitOrdered(CodeWriter w, ITypeSymbol element, bool canKey, AttributeData? attribute,
        EqualityTarget root, string comparer, string? customComparer, string left, string right, string compare,
        string failure, SourceProductionContext spc)
    {
        if (canKey && GenCommon.TryGetKeySpec(element, attribute, root, out var keyType, out var expression))
        {
            var elementName = element.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var describe = "ComparisonHelpers.DescribeOrderedByKey<" + elementName + ", " + keyType + ", " + comparer +
                           ">(" + left + ", " + right + ", static item => " + string.Format(expression, "item") +
                           ", new " + comparer + "(" + (customComparer ?? "") + "), context)";
            w.If("!(" + left + " is not null && " + right + " is not null && context.IsCollectingChanges ? " +
                 describe + " : " + compare + ")", () => w.Line(failure));
            return;
        }
        if (attribute?.NamedArguments.Any(pair => pair.Key == "KeyMembers" && pair.Value.Values.Length > 0) == true)
            spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ003,
                attribute.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation(), element));
        w.If("!" + compare, () => w.Line(failure));
    }

    private static void EmitUnordered(CodeWriter w, ITypeSymbol elementType, AttributeData? attribute,
        EqualityTarget root, string comparer, string? customComparer, string left, string right, SourceProductionContext spc)
    {
        var elementName = elementType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var arguments = left + ", " + right;
        var comparerExpr = "new " + comparer + "(" + (customComparer ?? "") + ")";
        string call;
        if (GenCommon.TryGetKeySpec(elementType, attribute, root, out var keyType, out var keyExpression))
        {
            call = "AreEqualSequencesByKey<" + elementName + ", " + keyType + ", " + comparer + ">(" +
                   arguments + ", static item => " + string.Format(keyExpression, "item") + ", " + comparerExpr + ", context)";
        }
        else
        {
            if (attribute?.NamedArguments.Any(pair => pair.Key == "KeyMembers" && pair.Value.Values.Length > 0) == true)
                spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.EQ003,
                    attribute.ApplicationSyntaxReference?.GetSyntax(spc.CancellationToken).GetLocation(), elementName));

            var deep = GenCommon.GetEffectiveKind(elementType, null) == EffectiveKind.Deep;
            call = customComparer is null && deep && GenCommon.IsHashFriendly(elementType)
                ? "AreEqualSequencesUnorderedHash(" + arguments + ", " + GenCommon.GetEqualityComparerExprForHash(elementType, "context", null) + ")"
                : "AreEqualSequencesUnordered<" + elementName + ", " + comparer + ">(" + arguments + ", " + comparerExpr + ", context)";
        }
        w.If("!ComparisonHelpers." + call, () => w.Line("return false;"));
    }

    private void EmitNullableValueCompare_NoCustom(CodeWriter w, string leftExpr, string rightExpr, ITypeSymbol valueType, string failure)
    {
        if (GenCommon.TryEmitWellKnownStructCompare(w, leftExpr + ".Value", rightExpr + ".Value", valueType, failure)) return;

        if (valueType.TypeKind == TypeKind.Enum)
        {
            var enumFqn = valueType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualEnum<" + enumFqn + ">(" + leftExpr +
                  ".Value, " + rightExpr + ".Value)", () =>
                  {
                      w.Line(failure);
                  });
            return;
        }

        if (valueType.SpecialType == SpecialType.System_String)
        {
            w.If("!DeepEqual.Generator.Shared.ComparisonHelpers.AreEqualStrings(" + leftExpr + ".Value, " +
                  rightExpr + ".Value, context)", () =>
                  {
                      w.Line(failure);
                  });
            return;
        }

        if (GenCommon.IsNumericWithTolerance(valueType))
        {
            var call = GenCommon.GetNumericCall(valueType, leftExpr + ".Value", rightExpr + ".Value", "context");
            w.If("!" + call, () =>
            {
                w.Line(failure);
            });
            return;
        }

        if (valueType.IsValueType && valueType.SpecialType != SpecialType.None)
        {
            w.If("!" + leftExpr + ".Value.Equals(" + rightExpr + ".Value)", () =>
            {
                w.Line(failure);
            });
            return;
        }

        if (valueType is INamedTypeSymbol namedTypeSymbol && GenCommon.IsUserObjectType(namedTypeSymbol)
                                                          && !(namedTypeSymbol.IsAbstract ||
                                                               namedTypeSymbol.TypeKind == TypeKind.Interface))
        {
            var helperExpr = GenCommon.GetHelperMethodName(namedTypeSymbol) + "(" + leftExpr + ".Value, " + rightExpr +
                             ".Value, context)";
            w.If("!" + helperExpr, () =>
            {
                w.Line(failure);
            });
            return;
        }

        w.If("!object.Equals(" + leftExpr + ".Value, " + rightExpr + ".Value)", () =>
        {
            w.Line(failure);
        });
    }


